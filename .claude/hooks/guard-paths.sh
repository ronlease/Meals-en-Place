#!/usr/bin/env bash
# PreToolUse (Edit|Write): block edits to generated and protected paths.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
read_input

file_path="$(json_get tool_input.file_path)"
[[ -z "$file_path" ]] && exit 0
rel="$(normalize_path "$file_path")"

case "$rel" in
  */node_modules/* | node_modules/*)
    block "$rel is a dependency directory." ;;
  */bin/* | */obj/*)
    block "$rel is a build output." ;;
  */coverage/* | */coverage-*/* | coverage-*/*)
    block "$rel is a coverage output." ;;
  */package-lock.json | package-lock.json)
    block "$rel is generated. Change package.json and run npm install." ;;
  */Migrations/*.Designer.cs)
    block "$rel is generated by dotnet ef. Scaffold a new migration instead." ;;
  docs/c4/*.png)
    block "$rel is rendered. Edit the .puml and run ./scripts/render-c4.sh." ;;
  */recipes_data.csv)
    block "$rel is the Kaggle dataset. It is never edited or committed." ;;
esac

exit 0
